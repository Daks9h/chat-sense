import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive = true, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[20px] bg-[var(--card-bg)] border border-[var(--border-subtle)] shadow-[var(--card-shadow)] transition-all duration-200",
      interactive && "hover:-translate-y-[2px] hover:bg-[var(--card-bg-hover)] hover:border-[var(--border-hover)] hover:shadow-[var(--card-shadow-hover)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

